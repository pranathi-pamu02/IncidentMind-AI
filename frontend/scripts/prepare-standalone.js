const fs = require("node:fs");
const path = require("node:path");

const standaloneDirectory = path.resolve(".next/standalone");
const standaloneNextDirectory = path.join(standaloneDirectory, ".next");

if (!fs.existsSync(path.join(standaloneDirectory, "server.js"))) {
  throw new Error("Next.js standalone server was not generated by the production build.");
}

fs.mkdirSync(standaloneNextDirectory, { recursive: true });
fs.cpSync(path.resolve(".next/static"), path.join(standaloneNextDirectory, "static"), {
  recursive: true,
});

const publicDirectory = path.resolve("public");
if (fs.existsSync(publicDirectory)) {
  fs.cpSync(publicDirectory, path.join(standaloneDirectory, "public"), { recursive: true });
}
